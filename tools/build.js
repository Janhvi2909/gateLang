#!/usr/bin/env node
/*
 * Builds dist/GateLang.html: one self-contained file with every script,
 * the stylesheet and the fonts inlined. It opens by double-click, works
 * offline, and can be shared as a single attachment.
 *   node tools/build.js
 */
'use strict';
const fs = require('fs');
const path = require('path');
const root = path.join(__dirname, '..');
const read = (p) => fs.readFileSync(path.join(root, p), 'utf8');

let html = read('index.html');
let css = read('ui/styles.css').replace(/url\("fonts\/([^"]+)"\)/g, (_, f) => {
  const data = fs.readFileSync(path.join(root, 'ui', 'fonts', f)).toString('base64');
  return `url("data:font/woff2;base64,${data}")`;
});
html = html.replace('<link rel="stylesheet" href="ui/styles.css">', () => `<style>\n${css}\n</style>`);
let count = 0;
html = html.replace(/<script src="([^"]+)"><\/script>/g, (_, src) => {
  count++;
  const code = read(src).replace(/<\/script/gi, '<\\/script');
  return `<script>/* ${src} */\n${code}\n</script>`;
});
const pkg = JSON.parse(read('package.json'));
html = html.replace('<head>', `<head>\n  <!-- GateLang ${pkg.version}: single-file build generated by tools/build.js -->`);
fs.mkdirSync(path.join(root, 'dist'), { recursive: true });
const out = path.join(root, 'dist', 'GateLang.html');
fs.writeFileSync(out, html);
console.log(`dist/GateLang.html written: ${count} scripts inlined, ${(fs.statSync(out).size / 1024).toFixed(0)} KB`);
